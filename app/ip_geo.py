def ip_to_coords(ip: str) -> tuple:
    if not ip or ip == "unknown":
        return (116.40, 39.90)

    try:
        parts = ip.split('.')
        if len(parts) != 4:
            return (116.40, 39.90)

        num = sum(int(p) * (256 ** (3 - i)) for i, p in enumerate(parts))

        city_names = list(CHINA_CITY_COORDS.keys())

        index = (num // 10000000) % len(city_names)
        city = city_names[index]

        base_coords = CHINA_CITY_COORDS[city]

        offset_lng = (num % 10000) / 10000.0 - 0.5
        offset_lat = ((num // 10000) % 10000) / 10000.0 - 0.5

        lng = base_coords[0] + offset_lng * 2
        lat = base_coords[1] + offset_lat * 2

        return (round(lng, 2), round(lat, 2))
    except:
        return (116.40, 39.90)

def ip_to_city(ip: str) -> str:
    if not ip or ip == "unknown":
        return "北京"

    try:
        parts = ip.split('.')
        if len(parts) != 4:
            return "北京"

        num = sum(int(p) * (256 ** (3 - i)) for i, p in enumerate(parts))

        city_names = list(CHINA_CITY_COORDS.keys())
        index = (num // 10000000) % len(city_names)
        return city_names[index]
    except:
        return "北京"

