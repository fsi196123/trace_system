def get_heatmap_data(ips: list) -> list:
    coords_map = {}
    for ip in ips:
        coords = ip_to_coords(ip)
        key = f"{coords[0]},{coords[1]}"
        if key in coords_map:
            coords_map[key] += 1
        else:
            coords_map[key] = 1

    result = []
    for key, count in coords_map.items():
        lng, lat = map(float, key.split(','))
        result.append([lng, lat, count])

    return result